/* =========================
   PERSIAN NUMBERS
========================= */

function persianNumber(number) {

  const numbers = [
    "۰",
    "۱",
    "۲",
    "۳",
    "۴",
    "۵",
    "۶",
    "۷",
    "۸",
    "۹"
  ];

  return String(number)
    .split("")
    .map(
      n => numbers[n] || n
    )
    .join("");
}


/* =========================
   SHOW PAGE
========================= */

function showPage() {

  const data =
    pages[currentPage];

  if (!data) {
    return;
  }


  content.innerHTML = `
    <h2>${data.title}</h2>
    ${data.content}
  `;


  const current =
    persianNumber(
      currentPage + 1
    );


  const total =
    persianNumber(
      TOTAL_PAGES
    );


  pageNumber.textContent =
    current;


  pageInfo.textContent =
    `${current} / ${total}`;


  const percent =
    ((currentPage + 1) /
      TOTAL_PAGES) * 100;


  progress.style.width =
    `${percent}%`;


  prevBtn.disabled =
    currentPage === 0;


  nextBtn.disabled =
    currentPage ===
    TOTAL_PAGES - 1;


  firstBtn.disabled =
    currentPage === 0;


  lastBtn.disabled =
    currentPage ===
    TOTAL_PAGES - 1;


  page.style.transform =
    `scale(${zoom})`;


  localStorage.setItem(
    "bookPage",
    currentPage
  );


  updateActiveTOC();

}


/* =========================
   NEXT PAGE
========================= */

function nextPage() {

  if (
    currentPage <
    TOTAL_PAGES - 1
  ) {

    currentPage++;

    showPage();

    page.scrollTop = 0;

  }

}


